/* 返回 { buy, gain }：
   buy 是给列表看的完整文案，gain 是纯收益句。
   写进故事脚本时直接用 gain，不再靠事后切分字符串去猜哪半句才是"收益" */
function translate(sell, dim, rand, cat, usedBuy) {
  const hit = matchBuy(sell, cat, usedBuy);
  if (hit) {
    if (usedBuy) usedBuy.add(hit.b);
    return { buy: hit.b, gain: hit.b };          // 品类库里成熟的翻译，本身就是收益句
  }
  let pool;
  if (/^(0|无|不含|零)|无添加|零添加|不含/.test(sell)) pool = CLEAN_TPL;
  else if (/\d+\s*(%|％|克|g|ml|毫升|倍|天|小时|分钟|秒|w|W|V|mA|mAh)/.test(sell)) pool = PARAM_TPL;
  else if (/(可食用|可用|适用|适合|能用|都能用|人群)/.test(sell)) pool = FIT_TPL;
  else pool = (TRANSLATE[dim] || TRANSLATE.func).map(t => [t, '']);
  const pick = pool[Math.floor(rand() * pool.length)];
  const tpl = pick[0];
  const buy = tpl.replace('{X}', sell);
  // 两段式模板的 [1] 就是纯收益句；单段模板从 {X} 之后截取
  const tail = pick[1] || tpl.slice(tpl.indexOf('{X}') + 3).replace(/^[—–-\s，,]+/, '').trim();
  return { buy, gain: tail || buy };
}

