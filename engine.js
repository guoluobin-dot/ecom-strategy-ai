const asText = v => (v == null ? '' : String(v));

function splitPoints(text) {
  const s0 = asText(text);
  if (!s0) return [];
  return s0
    .replace(/\r/g, '')
    .split(/[\n。！？!?；;]+/)
    .map(s => s.trim())
    .filter(s => s.length >= 2 && s.length <= 60)
    .slice(0, 14);
}

