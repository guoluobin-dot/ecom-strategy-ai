/* 上位词不能赢过下位词：写「食品生鲜」应该进食品生鲜，而不是因为「食品」
   两个字被前面的零食品类抢走。
   规则：取命中关键词最长的品类；长度相同时取靠后的（后加入的品类通常更细，
   比如「生鲜」和「食品」都命中时，"食品生鲜"比"零食"更贴合原意）。 */
function matchCategory(text) {
  // 表单/历史里的字段类型不保证是字符串，数字或对象也要能安全处理
  const t = (text == null ? '' : String(text)).trim();
  let best = null, bestLen = 0;
  for (const c of KB) {
    for (const m of c.match) {
      if (!t.includes(m)) continue;
      if (m.length > bestLen) { best = c; bestLen = m.length; }
    }
  }
  if (!best) return GENERAL;
  // 等长时再看谁更靠后
  let alt = null;
  for (const c of KB) {
    for (const m of c.match) {
      if (t.includes(m) && m.length === bestLen) alt = c;
    }
  }
  return alt || best;
}

