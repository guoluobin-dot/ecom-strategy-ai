/* opt.insights：由 insights.js 聚合出的历史复盘结论。
   有它就会给每个矩阵组合打上"已验证/已验证跑不动"的标签。 */
function generateReport(input, opt) {
  input = input && typeof input === 'object' ? input : {};
  const ins = (opt && opt.insights) || null;
  const cat = matchCategory(input.category);
  const rand = mulberry32(hashSeed(JSON.stringify(input)));
  const play = PAIN_PLAYBOOK[asText(input.pain)] || {
    focus: '卖点清晰化 + 场景落地',
    rule: '先讲清卖点，再把卖点放进具体场景里，让用户看到自己',
    tactics: ['先讲一个用户认得出的场景', '再给一个具体的解决方案', '结尾给明确的行动指令']
  };

  /* ---- 用户输入卖点归类 ---- */
  const rawPoints = [];
  const pushPoint = t => {
    const s = asText(t).trim();
    if (s.length < 2) return;
    // 过长条目按顿号/逗号二次拆分，避免整段被塞进单一维度
    if (s.length > 30) {
      s.split(/[、,，]/).map(x => x.trim()).filter(x => x.length >= 2).forEach(x => rawPoints.push({ text: x }));
    } else {
      rawPoints.push({ text: s });
    }
  };
  pushPoint(input.selling);
  splitPoints(input.detail).forEach(pushPoint);

  // 合并相邻的并列短项（如 0防腐剂 / 0甜味剂 / 0焦糖色 → 一条），更接近原始写法
  const merged = [];
  rawPoints.forEach(p => {
    const short = p.text.length <= 8 && /^(0|无|不含|零)/.test(p.text);
    const prev = merged[merged.length - 1];
    if (short && prev && prev._short && prev._n < 6) {
      prev.text += '、' + p.text;
      prev._n++;
    } else {
      merged.push({ text: p.text, _short: short, _n: 1 });
    }
  });
  rawPoints.length = 0;
  merged.forEach(p => { delete p._short; delete p._n; rawPoints.push(p); });

  const dims = { func: [], effect: [], emotion: [], trust: [], diff: [] };
  rawPoints.forEach(p => {
    const d = classifyPoint(p.text);
    dims[d].push(p.text);
  });
  // 品类库补足
  Object.keys(dims).forEach(k => {
    const base = (cat.dims && cat.dims[k]) || [];
    base.forEach(b => { if (dims[k].length < 4 && !dims[k].includes(b)) dims[k].push(b); });
    while (dims[k].length < 3) dims[k].push(GENERAL.dims[k][dims[k].length % GENERAL.dims[k].length]);
    dims[k] = dims[k].slice(0, 4);
  });

  /* ---- 01 卖点拆解完成 ---- */
  /* 深度：把每条卖点配上"怎么讲"，并说明这一维在内容里承担什么任务。
     dims 保持纯字符串数组（渲染/导出/测试都依赖它），讲解语另存 dimGuide 对齐下标 */
  const dimGuide = {};
  Object.keys(dims).forEach(k => {
    const t = DIM_TASK[k];
    dimGuide[k] = { task: t.task, how: dims[k].map((_, i) => t.how[i % t.how.length]) };
  });

  /* ---- 02 人群 ---- */
  const audiences = cat.audiences.map(a => {
    const jitter = (v, amp, lo, hi) => clamp(Math.round(v + (rand() * amp * 2 - amp)), lo, hi);
    return {
      name: a.name, tag: a.tag, why: a.why,
      scores: {
        match: jitter(a.base.match, 5, 55, 97),
        pain: jitter(a.base.pain, 5, 50, 97),
        ease: jitter(a.base.ease, 6, 12, 72),
        pay: jitter(a.base.pay, 6, 45, 95),
        size: jitter(a.base.size, 6, 45, 92)
      }
    };
  });

  /* 深度：打分只说明"值不值得投"，还要说清"投给他意味着放弃谁、决策要走几步"。
     这两条才是拍内容时真正会用到的东西 */
  audiences.forEach((a, i) => {
    const others = audiences.filter((_, j) => j !== i).map(x => x.name.split(/[，,、]/)[0]);
    a.notFor = `不要用同一条视频去打动另外两类（${others.join('、')}）——他们的问题和这个产品不匹配，口径混了会让算法也看不懂该推给谁`;
    // 决策链路：用付费意愿 × 表达难度推需要几次触达
    const hard = a.scores.ease > 45 || a.scores.pay < 65;
    a.chain = hard
      ? `决策链路长（付费意愿 ${a.scores.pay}%、表达难度 ${a.scores.ease}%）：他需要 3 次以上触达才敢下单，所以内容要拆成系列反复讲，别指望一条视频成交`
      : `决策链路短（付费意愿 ${a.scores.pay}%、表达难度 ${a.scores.ease}%）：看到就能判断要不要买，内容只要把证据摆够，一次触达就能转化`;
  });
  const mainAud = audiences[0];

  /* ---- 03 场景 ---- */
  const scenes = (cat.scenes || GENERAL.scenes).map(g => {
    const r = sceneRule(g.k);
    return {
      k: g.k, level: r.level, tone: r.tone, why: r.why,
      items: g.items.map(it => ({ n: it.n, ins: it.ins, use: it.use }))
    };
  });
  const mainScene = scenes[0].items[0];
  const painScene = (scenes.find(s => s.k.includes('翻车')) || scenes[1]).items[0];

  /* ---- 04 买点翻译 ---- */
  const buyPoints = [];
  const seen = new Set();      // 去重：同一卖点不重复
  const usedBuy = new Set();   // 去重：同一买点文案不重复出现
  rawPoints.forEach(p => {
    if (buyPoints.length >= 6) return;
    if (seen.has(p.text)) return;
    seen.add(p.text);
    const dim = classifyPoint(p.text);
    const t = translate(p.text, dim, rand, cat, usedBuy);
    buyPoints.push({ sell: p.text, buy: t.buy, gain: t.gain, dim, proof: PROOF_OF[dim] });
  });
  (cat.buy || GENERAL.buy).forEach(b => {
    if (buyPoints.length >= 6) return;
    if (buyPoints.some(x => x.sell === b.s) || usedBuy.has(b.b)) return;
    usedBuy.add(b.b);
    const dim = classifyPoint(b.s);
    buyPoints.push({ sell: b.s, buy: b.b, gain: b.b, dim, proof: PROOF_OF[dim] });
  });
  while (buyPoints.length < 5) {
    const g = GENERAL.buy[buyPoints.length % GENERAL.buy.length];
    buyPoints.push({ sell: g.s, buy: g.b, gain: g.b, dim: 'func', proof: PROOF_OF.func });
  }
  // 深度：这条买点最容易被怎么讲错 + 需要什么证据才能立住
  buyPoints.forEach(b => {
    b.risk = riskOf(b.sell) || riskOf(b.buy) ||
      (b.dim === 'effect' ? '别把"效果"说成保证，改为"在什么条件下、我用了多久的感受是"' : '这条本身没有明显违禁词，但别在文案里叠加绝对化用语');
  });
  const coreBuy = buyPoints[0];

  /* ---- 05 测试矩阵 ---- */
  const hooks = cat.hooks || GENERAL.hooks;
  const props = cat.props || GENERAL.props;

  /* 画面主体用具体商品名而不是品类名 ——
     "画面主体是一箱水果" 比 "画面主体是食品生鲜" 出图准确得多。
     用户填了产品名就用用户的，否则用品类库里的代表商品。 */
  const userProd = asText(input.prodName).trim();
  const prodName = userProd || cat.prod || cat.name;
  const kpi = KPI_OF[asText(input.pain)] || DEFAULT_KPI;
  const matrixCount = 8;
  // 把所有 (场景组, 场景项) 摊平成一张清单再依次取，
  // 直接用 i%3 推算会漏掉后面的场景组（比如第 4 组"情绪场景"永远轮不到）
  const sceneSlots = [];
  scenes.forEach(g => g.items.forEach(it => sceneSlots.push({ g, it })));
  const matrix = [];
  // 「人群 × 场景 × 买点」必须两两不同。槽位数量不固定（场景项可能少于 8 个），
  // 光靠取模会绕回上一轮产生完全重复的组合，所以这里显式去重。
  const usedTriples = new Set();
  for (let i = 0; i < matrixCount; i++) {
    const a = audiences[i % audiences.length];
    const slot = sceneSlots[i % sceneSlots.length];
    const sGroup = slot.g, sItem = slot.it;
    let bpIdx = i;
    let bp = buyPoints[bpIdx % buyPoints.length];
    const keyOf = x => `${a.name}|${sGroup.k}｜${sItem.n}|${x.buy}`;
    let guard = 0;
    while (usedTriples.has(keyOf(bp)) && guard < buyPoints.length) {
      bpIdx++; bp = buyPoints[bpIdx % buyPoints.length]; guard++;
    }
    usedTriples.add(keyOf(bp));
    // 深度：为什么是这一组先拍 + 这条视频只盯哪两个数
    const why = `${a.tag === '主攻' ? '主攻人群' + a.name.split(/[，,、]/)[0] + '卖点匹配度最高' : a.name.split(/[，,、]/)[0] + '属于' + a.tag + '，先验证他'}` +
      `；${sGroup.k}冲突强度${sGroup.level === '高' ? '高' : '中'}` +
      `；"${bp.sell}"→${bp.buy.split('——')[0].split('，')[0]}这条翻译在本轮最需要被验证`;
    const script = buildScript({ aud: a.name, scene: sItem.n, sell: bp.sell, buy: bp.buy, hook: hooks[i % hooks.length], prod: prodName, price: input.price, painScene: painScene.n });
    const story = buildStory({ scene: sItem.n, sell: bp.sell, gain: bp.gain, price: input.price, painScene: painScene.n }, script);
    // 钩子先判定一次；没认出商品就补商品名，再按补后的文本定分类
    const rawHook = hooks[i % hooks.length];
    const hk0 = classifyHook(rawHook, prodName);
    const hkText = hk0.revealsProduct ? rawHook : revealHook(rawHook, prodName);
    const promptArg = {
      aud: a.name,
      scene: sItem.n,
      prod: prodName,
      props,
      story,
      sell: bp.sell,
      painScene: painScene.n,
      proofItem: proofVisualOf(bp.dim, bp.sell),
      // 画面文字用补齐后的钩子；截断后如果把商品名切掉了，就直接用商品名兜底，
// 保证 0-3s 那行大字一定认得出在卖什么
      shotText: shotTextThatReveals(hkText, prodName),
        shotTextSell: shortShotText(bp.sell),
      person: personAnchor(a.name),
      personEn: personAnchorEn(a.name),
      prodAnchor: productAnchor(prodName),
      styleTone: sGroup.tone || '暖调'
    };
    promptArg.proofItemEn = enProofVisual(promptArg.proofItem);
    matrix.push({
      idx: i + 1,
      audience: a.name,
      scene: `${sGroup.k}｜${sItem.n}`,
      buyPoint: bp.buy,
      sellPoint: bp.sell,
      priority: i < 3 ? '优先测试' : (i < 6 ? '次轮测试' : '观察测试'),
      why,
      kpi: kpi.slice(),
      story,
      script,
      prompt: buildPrompt(promptArg),
      promptEn: buildPromptEn(promptArg)
    });
  }
  /* 内容策略字段（类型 / 角色 / 钩子分类 / 产品露出）统一在这里补，
     大模型那条路也调同一个函数 —— 两边各判一套必然对不上。 */
  assignStrategy(matrix, {
    hooks,
    prodName,
    audienceOf: i => audiences[i % audiences.length].name
  });

  /* 先打上历史验证标签，再排行动清单 —— 已验证跑得动的组合要优先推荐 */
  const insResult = (ins && typeof applyInsights === 'function') ? applyInsights(ins, matrix) : null;

  /* 深度：先做哪三件事。报告最前面给可执行清单，而不是让人自己从 8 组里挑 */
  const pick = matrix.slice()
    .sort((x, y) => {
      const px = x.proven && x.proven.level === 'win' ? 1 : 0;
      const py = y.proven && y.proven.level === 'win' ? 1 : 0;
      if (px !== py) return py - px;                 // 已验证的排前面
      const lx = x.proven && x.proven.level === 'lose' ? 1 : 0;
      const ly = y.proven && y.proven.level === 'lose' ? 1 : 0;
      if (lx !== ly) return lx - ly;                 // 跑动过的排后面
      return x.idx - y.idx;                            // 其余保持原顺序
    })
    .slice(0, 3);
  const actions = pick.map((m, i) => ({
    no: i + 1,
    what: `拍第${m.idx}组：${m.audience} × ${m.scene}` +
      (m.proven && m.proven.level === 'win' ? '（历史已验证跑得动）' : ''),
    how: `盯${m.kpi.slice(0, 2).join(' 和 ')}，` +
      (m.proven && m.proven.level === 'win' ? '这组有历史数据支撑，可直接扩量'
        : m.proven && m.proven.level === 'lose' ? '这组历史表现偏弱，当对照组看'
        : m.priority === '优先测试' ? '这组跑通再扩量' : '作为对照'),
    when: '本周内，和另外两组同期发布，避免互相干扰'
  }));

  return {
    meta: {
      category: asText(input.category).trim() || '未填写',
      prodName: prodName,
      price: asText(input.price).trim() || '未选择',
      aov: asText(input.aov).trim() || '未填写',
      selling: asText(input.selling).trim() || '未填写',
      pain: asText(input.pain).trim() || '未选择',
      catName: cat.name,
      date: asText(input.date) || '未填写'
    },
    play,
    summary: {
      audience: mainAud.name,
      audienceWhy: mainAud.why,
      buyPoint: coreBuy.buy,
      scene: `${scenes[0].k}｜${mainScene.n}`,
      sceneIns: mainScene.ins
    },
    actions,
    dimGuide,
    dims,
    audiences,
    scenes,
    buyPoints,
    matrix,
    /* 内容策略总表：一个核心方向 + 几个辅助方向，各承担不同角色 */
    typePlan: buildTypePlan(matrix),
    insights: insResult
  };
}

/* ---------------- 脚本生成 ----------------
   脚本最终形态是"一整段话"。分镜表格只是中间产物（也用于兜底与导出），
   报告与提示词都以 story 这段话为准。 */
function buildScript(o) {
  const priceSeg = o.price ? o.price + '这个价位' : '这个价位';
  // v 列是"画面里有什么"，不是拍摄方法。写给 AI 视频模型看。
  const rows = [
    {
      t: '0-3s', stage: '钩子',
      l: o.hook,
      v: `${o.aud}拿着${o.prod}，停在最狼狈的一瞬，表情是刚发现问题的惊讶；${o.scene}真实环境，自然光侧照，手持轻微晃动推近到半脸`
    },
    {
      t: '3-8s', stage: '痛点',
      l: `${o.aud}，最常卡住的就是「${o.scene}」——${o.painScene}。不是你的问题，是之前的东西没解决这个问题。`,
      v: `${o.aud}被${o.painScene}困住，摊手或皱眉看向镜头；光线偏冷、环境更杂乱，冷调顶部光，轻微横移`
    },
    {
      t: '8-15s', stage: '演示',
      l: `我的做法是：${o.sell}。说人话就是——${o.buy}。`,
      v: `双手使用${o.prod}，产品占画面中心、动作完整可看清；干净台面只留本体，柔和侧光突出质感，镜头轻微推近`
    },
    {
      t: '15-22s', stage: '证据',
      l: `不是我自己说好：检测报告/实测数据在这里，${priceSeg}能做到这一点的不多。`,
      v: `检测报告或数据画面占 2/3 画幅、文字清晰可辨，旁边并排两个数据对比；纯色背景、无反光，完全静止`
    },
    {
      t: '22-28s', stage: '行动',
      l: `${o.price ? '现在' + o.price + '这个档位' : '这个价位'}，可以先按最小规格试一次，不合适还有退换。想要同款的，评论区扣「1」。`,
      v: `${o.prod}静置画面中央偏右，人物半身微笑看向镜头；环境明亮整洁，暖调通透光，缓慢拉远留呼吸感`
    }
  ];
  return rows;
}

/* 把 5 段串成一段能直接念的口播稿：钩子抛问题 → 痛点共情 → 演示给做法 →
   证据打消顾虑 → 行动收口。整段无换行、无编号、无人称跳变。
   这是报告和视频提示词的唯一事实来源，分镜表只是它的拆解视图。 */
/* 故事脚本是给用户念的，不能出现写给内部看的话（"本组""矩阵""这条视频"等）。
   钩子库这类素材最容易混进内部话术，出口统一过一道闸。 */
const INNER_WORDS_ENGINE = /本组|这条视频|这条内容|矩阵|策略重心|测试组合|脚本|分镜|卖点拆解/;
function noInnerWords(s) {
  return INNER_WORDS_ENGINE.test(asText(s));
}

function buildStory(o, rows) {
  const priceSeg = o.price ? o.price + '这个价位' : '这个价位';
  const r = rows || [];
  const at = i => {
    const t = String((r[i] && r[i].l) || '').trim();
    return noInnerWords(t) ? '' : t;
  };
  const raw = at(0);
  const hook = raw.replace(/[。！？!?]+$/, '') + (raw ? '。' : '');
  // 收益句必须和卖点不同，否则"说白了就是X"等于把 X 又说一遍
  const bare = s => asText(s).replace(/[\s，。！？、；：·—–-]/g, '');
  const g0 = asText(o.gain).replace(/[。！？!?]+$/, '').trim();
  // 收益句本身可能以"说白了"开头，直接接进固定句式会变成"说白了就是说白了"
  const gain = g0.replace(/^(说白了|简单说|也就是说)[，,]?\s*/, '').trim() || g0;
  const gFinal = (g0 && bare(gain) === bare(o.sell)) ? '用起来就是不用再操心这件事' : gain;
  const scene = noInnerWords(o.scene) ? o.scene : '';
  const parts = [
    hook,
    scene && o.painScene ? `如果你也遇到过这种情况：${scene}的时候，${o.painScene}，那种感觉不用我多说你肯定懂。` : '',
    o.sell ? `我的解法其实很简单——${o.sell}${gFinal ? '，说白了就是' + gFinal : ''}。` : '',
    `我知道你在想什么，所以这次我没打算只靠嘴说：实测数据、检测报告都在这儿，${priceSeg}能做到这个的，真不多。`,
    `${o.price ? '现在' + o.price + '这个档位' : '这个价位'}，先按最小规格试一次，不合适还能退。想看实测的，评论区扣个「1」，我把细节发你。`
  ];
  return parts.filter(Boolean).join('').replace(/\s+/g, ' ').trim();
}

/* ---------------- 英文版提示词 ----------------
   Sora / Runway / Veo 等模型对英文提示词的响应明显好于中文，所以视觉描述必须有英文版。
   两个刻意的取舍：
     1) 画面里的文字仍写中文 —— 国内平台观众看中文，商品规格也通常不翻译。
     2) audience / scene / prodName 是中文，本地引擎无法高质量翻译。
        这里把固定的画面结构（运镜/光线/环境）用英文模板写死，
        主体与卖点原样保留并标成 [CHINESE: ...]，提示使用者替换。
        接入大模型时让它直接产出完整英文版，那时才是一开箱即用。 */
function buildShotPromptEn(o, beat) {
  const prod = o.prod;
  switch (beat) {
    case 'hook':
      return `Medium close-up of a shopper holding ${prod} [CHINESE: ${prod}], caught at the worst possible moment — a messy desk, a low-battery warning, or the box just opened. Expression: genuine surprise, mid-reaction.\n` +
        `Setting: a real lived-in room, not a showroom; everyday clutter on the desk, natural wear and marks.\n` +
        `Lighting: soft natural daylight from the front-left, gentle shadows, no harsh flash.\n` +
        `Camera: handheld, slight natural sway, slow push-in to a medium close-up.\n` +
        `On-screen text (Chinese): "${o.shotText}" — bold sans-serif, white with subtle outline, top center.`;
    case 'pain':
      return `Medium shot of a shopper [CHINESE audience: ${o.aud}], visibly frustrated — hands spread apart or brow furrowed, looking toward camera. Exaggerated, relatable body language.\n` +
        `Setting: same location but dimmer and messier, conveying irritation.\n` +
        `Lighting: cooler tone, harder overhead light, slightly desaturated.\n` +
        `Camera: handheld, slow lateral tracking move.\n` +
        `On-screen text: none.`;
    case 'demo':
      return `Close-up of hands using ${prod} [CHINESE: ${prod}]. The product sits at the center of frame; the full motion is clearly visible from start to finish.\n` +
        `Setting: clean surface in a ${o.scene} [CHINESE: ${o.scene}], product only, no clutter.\n` +
        `Lighting: soft side light revealing surface texture and hand detail.\n` +
        `Camera: locked-off with a very slow push-in, product stays centered.\n` +
        `On-screen text (Chinese): "${o.shotTextSell}" — single line, bottom center, small and non-obstructive.`;
    case 'proof':
      return `Macro shot of ${o.proofItemEn || 'the product spec label'}, filling two thirds of the frame; printed text and numbers clearly legible.\n` +
        `Beside it, a side-by-side data comparison of two options (left: generic, right: this product), figures readable.\n` +
        `Setting: plain solid-color background, nothing else in frame.\n` +
        `Lighting: flat even light, no reflections obscuring text.\n` +
        `Camera: completely static, held long enough to read.\n` +
        `On-screen text: key figures highlighted in large numerals.`;
    case 'cma':
      return `The ${prod} [CHINESE: ${prod}] resting at center-right of frame, slightly angled; a hand gestures toward it, or the shopper appears in a medium shot smiling at camera.\n` +
        `Setting: a clean, bright ${o.scene} [CHINESE: ${o.scene}].\n` +
        `Lighting: bright and airy, warm neutral tones, high-key.\n` +
        `Camera: slow pull-back, leaving breathing room for the end card.\n` +
        `On-screen text (Chinese): "${o.shotText}" — bottom center.`;
    default:
      return prod;
  }
}

function consistencyAnchorEn(o) {
  return [
    '【④ CONSISTENCY ANCHOR — EN】Prepend this block to EVERY shot prompt, otherwise each shot renders a different person and a different-looking product.',
    `Character: ${o.personEn} — identical face, hairstyle and clothing in every shot.`,
    `Product: ${o.prod} [CHINESE: ${o.prod}] — identical shape, color, material and logo placement in every shot.`,
    'Lighting: one consistent setup for the whole video; key light always from front-left; shadow direction never changes.',
    'Look: a single consistent render style, same color science and contrast throughout.',
    'If your tool supports a character reference image or a fixed seed, reuse the same value for every shot.'
  ].join('\n');
}


function buildPromptEn(o) {
  const shots = SHOT_BEATS.map(b => ({ span: b.span, text: buildShotPromptEn(o, b.key) }));
  // 与中文版同理给默认值：props 为空时不要三处都退化成同一句
  const p1 = enProp((o.props && o.props[0]) || '产品特写');
  const p2 = enProp((o.props && o.props[1]) || '使用演示');
  const p3 = enProp((o.props && o.props[2]) || '细节特写');
  return [
    '【① VOICEOVER】Narrate this separately via TTS or subtitles — it is not part of the visual prompt.',
    o.story,
    '',
    '【② SHOT PROMPTS — EN】One block per shot; paste each one individually.',
    ...shots.map(s => `${s.span} — ${s.text}`),
    '',
    '【③ GLOBAL STYLE — EN】Prepend or append to every shot for a consistent look.',
    'Live-action realism, low commercial polish, natural daylight, no beauty-filter skin. Vertical 9:16, 1080x1920, about 8 seconds, 30fps.',
    `Color: ${/冷/.test(o.styleTone || '') ? 'cool' : 'warm'} tones, moderate saturation, soft shadows.`,
    `Texture: alternate between ${p1}, ${p2} and ${p3}; product detail stays sharp.`,
    'Negative: overexposure, plastic skin, cluttered background, extra text, watermark, deformed hands, duplicated faces.'
  ].join('\n') + '\n\n' + consistencyAnchorEn(o);
}

/* 证据画面（PROOF_VISUAL 的中文值）转成英文 */
function enProofVisual(cn) {
  const s = asText(cn);
  if (/检测|资质/.test(s)) return 'a third-party test report or certification document';
  if (/对比表|参数/.test(s)) return 'a printed spec sheet showing two products side by side';
  if (/评价/.test(s)) return 'a screenshot of genuine customer reviews';
  if (/前后对比/.test(s)) return 'a before-and-after comparison image';
  return 'the product spec label';
}

/* 素材词表是中文，英文版里换成通用说法（画质描述，不是具体指令） */
function enProp(cn) {
  const s = asText(cn);
  if (/特写|微距|细节/.test(s)) return 'sharp detail macro shots';
  if (/全景|环境|场景|收纳|桌面/.test(s)) return 'wide environmental shots';
  if (/对比|同框|横评/.test(s)) return 'side-by-side comparison shots';
  if (/参数|数字|检测|成分|报告/.test(s)) return 'on-screen data and label close-ups';
  if (/演示|操作|使用|过程|冲泡/.test(s)) return 'clear in-use demonstration shots';
  return 'clean product shots';
}

/* ---------------- AI 视频生成提示词 ----------------
   目标读者是 AI 视频模型，不是摄影师。
   所以只描述"画面里有什么"，不出现机位、实拍、补拍这类拍摄术语。
   三段式：① 剧情梗概（配音稿）② 分镜画面提示（逐条可直接粘贴）③ 整体风格。 */

const SHOT_BEATS = [
  { key: 'hook',  span: '0-3s' },
  { key: 'pain',  span: '3-8s' },
  { key: 'demo',  span: '8-15s' },
  { key: 'proof', span: '15-22s' },
  { key: 'cma',   span: '22-28s' }
];

/* 内容类型：抖音跑量的六大模板，跨品类通用，不用每类重写。
   为什么要分类：同一个产品同一种剧情，开头有没有让人认出"这是卖什么"，
   播放量能差几十倍。类型不同，承担的角色也不同 —— 一个品牌是
   1 个核心方向 + 3~5 个辅助方向拼成策略，不是一堆同质化视频。
   跑量最大的是剧情类和痛点类，所以这两类排在前面。 */
const CONTENT_TYPES = [
  { k: '剧情', why: '靠冲突和反转留人，最容易起量' },
  { k: '痛点', why: '直接戳人群的麻烦，看到就想解决' },
  { k: '场景', why: '让人想起自己用过它的那个时刻' },
  { k: '种草', why: '像朋友推荐，专治"信不信"' },
  { k: '促销', why: '价格对比逼单，适合临门一脚' },
  { k: '证据', why: '拿能验证的东西把话说死' }
];
/* 人群名里出现这些词，说明这群人先看证据再下单 —— 偏理性/慢热/要托底。
   视频里的原话是：老抽配搞笑婆媳剧情跑不动，因为买老抽的是做饭的人，
   她不吃这一套 —— 题材和人群不匹配，再好的画面也白搭。
   所以不是配完了再提醒，是一开始就别把剧情类派给这些人。 */
function isSlowHeat(audName) {
  const a = asText(audName);
  return /(中老年|退休|祖辈|长辈|50\s*岁以上|商务|企业|决策|理性|严谨|专业)/.test(a) ||
    // 代买/孝心/成分党这类"先看证据再下单"的
    /(给父母|长辈代买|代买|关注父母健康|成分党|注重.*(品质|产地|成分))/.test(a);
}
/* 这类人群换成哪种类型 */
function typeAlt(audName) {
  return /(成分|品质|产地|商务|企业|决策|专业|严谨|理性)/.test(asText(audName)) ? '证据' : '痛点';
}

/* 钩子分类：视频点名的高点击开头是 猎奇 / 痛点 / 情感共鸣 / 直观效果，
   再加一条硬规则 —— 前三秒必须让人看出这是卖什么的。
   同样卖笔带，一个开头就让人认出产品（十几万播放），
   另一个到第三秒还不知道卖什么（一两千播放）。 */
const HOOK_KINDS = ['产品露出', '痛点', '情感共鸣', '直观效果', '猎奇'];
/* 带数量或规格的句子（"同样五斤""16块"）同样说明在讲这个商品，算已露出 */
const QUANTITY_RE = /\d+\s*(块|斤|克|ml|ML|L|升|片|只|个|支|条|盒|包)/;
/* 商品短名：取第一个逗号/顿号/空格前的部分，"Dior 999 哑光唇釉 蜜桃色" → "Dior" */
function shortProdName(prod) {
  return asText(prod).trim().split(/[，,、\s]/)[0] || '';
}
function classifyHook(hook, prod) {
  const t = asText(hook);
  let k = '猎奇';
  if (/给(爸妈|家人|孩子|老人)|顺手|顺手带|给.{0,4}寄/.test(t)) k = '情感共鸣';
  else if (/别再|老是|总是|踩坑|白买|又|难|烦|累|受不了|抓狂|后悔/.test(t)) k = '痛点';
  else if (/省了|省下|直接|一[瓶个斤盒]|终于|居然|原来|这样就/.test(t)) k = '直观效果';
  const reveal = mentionsProduct(t, prod) || QUANTITY_RE.test(t);
  return { kind: reveal ? '产品露出' : k, revealsProduct: !!reveal };
}

/* 钩子没认出产品时的补救：把商品塞进开头。
   视频里的原话是同样卖笔带，一个开头就让人认出产品（十几万播放），
   另一个到第三秒还不知道卖什么（一两千播放）。所以这条必须兜住。 */
function revealHook(hook, prod) {
  const t = asText(hook).trim();
  if (!asText(prod).trim()) return t;
  if (mentionsProduct(t, prod)) return t;
  // 已经带规格或数量的（"同样五斤"）也算有信息，不硬塞
  if (QUANTITY_RE.test(t)) return t;
  // 放句首而不是句末：开口第一句就报商品名，听众第一时间知道在卖什么
  return `${shortProdName(prod)}，${t.replace(/[。！？]+$/, '')}`;
}

/* 判断一段文字里有没有认出这个商品。
   中文取前 2 个字就够（"产地直发"里含"产地"）；拉丁品牌名不能这么切，
   "Dior" 含 "Di"，会把 "Dior 999 哑光唇釉" 误判成已露出还被截断成 "Dior"。 */
function mentionsProduct(text, prod) {
  const t = asText(text).replace(/\s+/g, '');
  const name = shortProdName(prod).replace(/\s+/g, '');
  if (!name) return false;
  if (/[A-Za-z]/.test(name)) {
    // 拉丁名（含品牌+型号）必须整段或整词出现
    return new RegExp('(^|[^A-Za-z0-9])' + name.replace(/[.*+?^${}()|[\]\\]/g, '') + '($|[^A-Za-z0-9])', 'i')
      .test(asText(text));
  }
  return t.includes(name.slice(0, 2));
}

/* 画面大字：短，但必须在 3 秒内认出商品。
   商品名被放句首后，shortShotText 只会截出商品名那一句，8 条视频会长得一模一样，
   所以这里跨过商品名、接上钩子核心，两段合成一行大字。 */
function shotTextThatReveals(hook, prod) {
  const p = asText(prod).trim();
  if (!p) return shortShotText(hook);
  const raw = asText(hook).trim();
  const name = shortProdName(prod);
  const one = shortShotText(raw);
  // 截断结果里既认出商品、又还带着钩子的实质内容，才直接用。
  // 只剩一个商品名的话，8 条视频开头会长得一模一样，等于白写钩子。
  if (mentionsProduct(one, p) && one.length > name.length + 1) return one;
  const clauses = raw.split(/[，,。！？、;；]/).map(s => s.trim()).filter(Boolean)
    .filter(s => !mentionsProduct(s, p) && s !== name);
  if (!clauses.length) return name.slice(0, 13);
  const core = clauses[0].slice(0, 11);
  const joined = `${name} ${core}`;
  if (joined.length <= 13) return joined;
  // 超长时砍商品名、不砍钩子核心 —— 认出商品是硬要求，钩子可以短
  //（砍核心会退回成光秃秃的商品名，8 条视频开头一模一样）
  return `${name.slice(0, 5)} ${core.slice(0, 7)}`;
}

/* 内容策略总表：一个核心方向 + 3~5 个辅助方向。
   每条视频承担不同角色，而不是一堆同质化视频 —— 这是策略，不是素材堆量。
   开头没认出产品的要标出来，因为那是播放量差几十倍的原因。 */
function buildTypePlan(matrix) {
  const byType = {};
  matrix.forEach(m => {
    if (!byType[m.type]) byType[m.type] = { type: m.type, role: m.typeRole, why: m.typeWhy, items: [], noReveal: 0, warns: [] };
    byType[m.type].items.push(m.idx);
    if (!m.hookRevealsProduct) byType[m.type].noReveal++;
    if (m.fitWarn) byType[m.type].warns.push(m.fitWarn);
  });
  return Object.keys(byType).map(k => byType[k]);
}

/* 画面里的大字要短。钩子常是整句话，直接塞进画面会变成一段话。
   按分隔符切，优先切出完整的一个语义单元（"当日采当日发"比"当日采当日发 坏果包赔"好） */
function shortShotText(hook) {
  const t = asText(hook).trim();
  const head = t.split(/[，,。！？、]/)[0] || t;
  // 复合卖点用空格分隔（"产地直发 冷链发货"），截断时要在空格处断开
  const bySpace = head.split(/\s+/).filter(Boolean);
  let out = head;
  if (out.length > 12 && bySpace.length > 1) {
    const one = bySpace[0];
    out = one.length <= 12 ? one : one.slice(0, 12) + '…';
  } else if (out.length > 12) {
    out = out.slice(0, 12) + '…';
  }
  return out;
}

/* 单条分镜的画面提示词：主体 + 动作 + 环境 + 光线 + 运镜 + 画面文字 */
function buildShotPrompt(o, beat) {
  const aud = o.aud, prod = o.prod, scene = o.scene;
  const base = `${aud}在${scene}，画面主体是${prod}`;
  switch (beat) {
    case 'hook':
      return `${base}，手里还拿着它，画面停在最狼狈的一瞬（电量告急/包装还没拆/东西散了一桌），人物表情是「发现问题」的惊讶。\n` +
        `环境：真实的${scene}环境，桌面/地面有生活痕迹，不要样板间感。\n` +
        `光线：室内自然光，从侧前方来，有轻微阴影。\n运镜：手持轻微晃动，缓慢推近到人物半脸。\n` +
        `画面文字：顶部居中大字「${o.shotText}」，无衬线粗体，白色加轻微描边。`;
    case 'pain':
      return `${base}，正被${o.painScene}的问题困住，双手一摊或皱眉看向镜头，动作夸张到能共情。\n` +
        `环境：同一地点但光线更暗一点，或更杂乱，突出烦躁感。\n` +
        `光线：冷调，顶部灯光偏硬。\n运镜：轻微手持，缓慢横移。\n` +
        `画面文字：无。`;
    case 'demo':
      return `${base}，正在使用${o.sell}，双手和产品占画面中心，动作清晰完整能看清怎么用。\n` +
        `环境：干净的${scene}台面，只留产品本体。\n` +
        `光线：柔和侧光，突出产品质感和手部细节。\n运镜：镜头轻微推近，产品保持画面中心不跑。\n` +
        `画面文字：底部一行「${o.shotTextSell}」，简洁不遮挡产品。`;
    case 'proof':
      return `画面主体切换为${o.proofItem}的特写，占据画面 2/3，上面的文字和数据清晰可辨；\n` +
        `旁边并排出现两个数据对比（左「普通款」右「本款」），数值清晰可读。\n` +
        `环境：纯色背景，无杂物。\n` +
        `光线：均匀无阴影，避免反光遮挡文字。\n运镜：完全静止，方便看清信息。\n` +
        `画面文字：数据用大号数字高亮。`;
    case 'cma':
      return `${prod}静置在画面中央偏右，人物的手指向它，或人物出镜半身微笑看向镜头。\n` +
        `环境：${scene}环境，干净整洁，光线明亮。\n` +
        `光线：明亮暖调，整体通透。\n运镜：缓慢拉远，给结尾留呼吸感。\n` +
        `画面文字：底部居中「${o.shotText}」。`;
    default:
      return base;
  }
}

/* ---------------- 跨镜头一致性 ----------------
   AI 视频是逐段独立生成的：不给固定的人物与商品描述，5 段会出 5 个不同的人、
   5 个不同颜色的商品，拼起来直接穿帮。所以每条分镜都带同一段"锚点"，
   让模型知道"从头到尾就是这一个人、这一个商品"。 */

/* 从已生成的分镜提示词里把钩子捞回来。
   AI 那条路没有 hooks 概念，但 0-3s 的画面文字就是钩子，
   从提示词反解出来才能接着判类型和"有没有露出产品"。 */
function hookFromPrompt(prompt) {
  const t = asText(prompt);
  const line = t.split('\n').find(l => l.indexOf('画面文字') >= 0);
  if (!line) return '';
  const m = line.match(/「([^」]+)」/);
  return m ? m[1] : '';
}

/* 给任意来源的矩阵补齐内容策略字段。本地引擎和大模型两条路共用，
   保证同一份输入不管谁生成，界面上的类型分工、角色、钩子分类都一致。
   ctx.audienceOf 提供"这一组对应哪个人群"——AI 可能改了人群，
   所以按行取而不是按索引硬套。 */
function assignStrategy(matrix, ctx) {
  const n = Math.max(1, matrix.length);
  // 与本地一致：8 组摊开 6 类；剧情类留给不必先看证据的人群；
  // 如果主攻人群就是慢热类型，把一个重复类型改回剧情，保证剧情不会整份消失。
  const plan = [];
  for (let i = 0; i < n; i++) {
    const aud = asText(ctx.audienceOf(i));
    let k = CONTENT_TYPES[i % CONTENT_TYPES.length].k;
    let switched = '';
    if (k === '剧情' && aud && isSlowHeat(aud)) {
      k = typeAlt(aud);
      switched = `${aud}先看证据才下单，剧情类靠情绪冲突容易投不动，已改成${k}类`;
    }
    plan.push({ k, switched });
  }
  if (n >= 4 && !plan.some(p => p.k === '剧情')) {
    const seen = {};
    plan.forEach(p => seen[p.k] = (seen[p.k] || 0) + 1);
    for (let i = 0; i < n; i++) {
      const aud = asText(ctx.audienceOf(i));
      if (aud && !isSlowHeat(aud) && seen[plan[i].k] > 1) {
        seen[plan[i].k]--;
        plan[i] = { k: '剧情', switched: `${aud}这类人不必先看证据，这组改回剧情类试起量` };
        break;
      }
    }
  }
  matrix.forEach((m, i) => {
    const p = plan[i] || { k: CONTENT_TYPES[i % CONTENT_TYPES.length].k, switched: '' };
    const meta = CONTENT_TYPES.filter(t => t.k === p.k)[0] || CONTENT_TYPES[0];
    const hooks = ctx.hooks || [];
    const raw = hooks.length ? hooks[i % hooks.length] : (ctx.hookOf ? ctx.hookOf(i) : '');
    let text = asText(raw), reveal = false, kind = '猎奇';
    if (text && ctx.prodName) {
      const h0 = classifyHook(text, ctx.prodName);
      if (h0.revealsProduct) { reveal = true; kind = h0.kind; }
      else { text = revealHook(text, ctx.prodName); kind = classifyHook(text, ctx.prodName).kind; reveal = true; }
    } else if (text) {
      const h0 = classifyHook(text, '');
      kind = h0.kind; reveal = h0.revealsProduct;
    }
    m.type = p.k;
    m.typeRole = i === 0 ? '核心方向' : (i < 6 ? '辅助方向' : '观察方向');
    m.typeWhy = meta.why;
    m.hookKind = kind;
    m.hookRevealsProduct = reveal;
    m.fitWarn = p.switched;
    // 钩子没露出产品时，画面大字要重新兜一遍，否则模型写偏的开头就漏过去了
    if (text && ctx.prodName && !m.hookRevealsProduct) {
      m.hookRevealsProduct = mentionsProduct(m.prompt, ctx.prodName);
    }
  });
  return matrix;
}

/* 人物设定的判定只做一次，中英文各自套一层说法。
   之前 personAnchor / personAnchorEn 各自复制了同一套正则梯子
   （年龄、性别、8 段身份分支），改一边忘另一边就会让中英文人设对不上。 */
const PERSONA_BY_ROLE = [
  [/(学生|备考|考公)/,                                     '20-25岁',   'early 20s', '穿卫衣的学生',         'wearing a hoodie'],
  [/(宝妈|妈妈|主妇|有娃|母婴|育儿)/,                '30岁左右', 'early 30s', '穿家居服的母亲',       'wearing casual home clothes'],
  [/(退休|中老年|祖辈|长辈|家务主力)/,          '55-70岁',   'early 60s', '穿简单外套的中老年人', 'wearing a plain zip-up jacket'],
  [/(上班族|职场|办公|通勤|白领|效率|固定坐班)/, '28-35岁',   'early 30s', '穿衬衫的上班族',       'wearing a button-up shirt'],
  [/(车主|汽车)/,                                            '28-35岁',   'early 30s', '穿外套的司机',         'wearing a light jacket'],
  [/(养宠|铲屎|宠物)/,                                '30岁左右', 'early 30s', '穿T恤的年轻人',        'wearing a plain t-shirt'],
  [/(穿搭|服饰|衣服|美妆|化妆|彩妆)/,              '30岁左右', 'early 30s', '穿着讲究的年轻人',     'in a put-together casual outfit'],
  [/(新手妈妈|二胎|新手车主|刚入坑|进阶玩家|资深)/, '30岁左右', 'early 30s', null,                   null],
  [/(中年|代买|子女|品质|中产)/,                        '35-45岁',   'mid 40s',   null,                   null]
];
const PERSONA_FALLBACK = ['30岁左右', 'early 30s', '穿日常便装的人', 'wearing everyday casual clothes'];

function personaOf(audName) {
  const n = asText(audName);
  const age = n.match(/(\d+)\s*-\s*(\d+)\s*岁/) || [];
  const over50 = /50\s*岁以上/.test(n);
  const elder = /(祖辈|爷爷奶奶|中老年|长辈|退休)/.test(n);
  // 年龄偏大时别再叫"年轻人"，也不该套黑色短发/淡妆这种年轻向描述
  const senior = over50 || elder;
  const female = /(女性|女生|宝妈|妈妈|孕|主妇|姑娘|女王)/.test(n);
  const male = /(男性|男生|车主.*男|先生|爸爸|父亲|主夫)/.test(n);
  const avg = age.length ? Math.round((+age[1] + +age[2]) / 2) : null;
  // 英文年龄用 early 30s / mid 40s 这类描述，不写精确数字（"a 33-year-old" 太机械）
  const decade = d => d < 20 ? 'late teens' : d < 25 ? 'early 20s' : d < 30 ? 'mid 20s' : d < 35 ? 'early 30s'
    : d < 40 ? 'late 30s' : d < 45 ? 'early 40s' : d < 50 ? 'mid 40s' : d < 58 ? 'late 50s' : 'early 60s';

  let byZh = null, byEn = null, roleZh = null, roleEn = null;
  for (const [re, zh, en, rz, rn] of PERSONA_BY_ROLE) {
    if (!re.test(n)) continue;
    if (byZh === null) { byZh = zh; byEn = en; }
    if (roleZh === null && rz) { roleZh = rz; roleEn = rn; }
    if (byZh !== null && roleZh !== null) break;
  }
  if (roleZh === null) {
    roleZh = senior ? '穿简单外套的中老年人' : PERSONA_FALLBACK[2];
    roleEn = senior ? 'wearing a plain jacket' : PERSONA_FALLBACK[3];
  }
  return {
    senior,
    yearsZh: over50 ? '50岁以上' : elder ? '55-70岁' : (avg !== null ? avg + '岁左右' : (byZh || PERSONA_FALLBACK[0])),
    yearsEn: over50 ? 'early 50s' : elder ? 'early 60s' : (avg !== null ? decade(avg) : (byEn || PERSONA_FALLBACK[1])),
    genderZh: senior ? '成年人' : female ? '女性' : (male ? '男性' : '年轻人'),
    genderEn: senior ? 'adult' : female ? 'woman' : (male ? 'man' : 'young adult'),
    lookZh: senior ? '短发或盘发，不化妆，状态自然' : '黑色短发，素颜或淡妆',
    // 英文版按性别区分发型和妆容，和中文"黑色短发，素颜或淡妆"的笼统说法对应
    lookEn: senior ? 'short or tied-back hair, no makeup'
      : female ? 'shoulder-length dark hair, natural brows, light makeup'
      : 'short dark hair, clean-shaven, natural skin',
    roleZh, roleEn
  };
}

function personAnchor(audName) {
  const p = personaOf(audName);
  const tail = p.senior ? '' : '，表情自然';
  return `一位${p.yearsZh}的${p.genderZh}，${p.roleZh}，${p.lookZh}${tail}`;
}

function personAnchorEn(audName) {
  const p = personaOf(audName);
  // "an early 30s woman" / "a late 50s adult" —— 注意冠词 a/an
  const art = /^[aeiou]/i.test(p.yearsEn) ? 'an' : 'a';
  return `${art} ${p.yearsEn} ${p.genderEn} ${p.roleEn}, ${p.lookEn}`;
}

function productAnchor(prodName) {
  const p = asText(prodName);
  // 产品名里带颜色/材质就沿用，否则给一个中性的常见外观
  const color = (p.match(/(黑|白|红|蓝|绿|灰|粉|金|银|棕|米|藏青|透明)/) || [])[1];
  const material = /(玻璃|陶瓷|不锈钢|铝合金|硅胶|木质|皮革|棉|塑料|金属)/.exec(p);
  const parts = [`${p}`];
  parts.push(color ? `${color}色` : '主体颜色与包装一致');
  if (material) parts.push(material[1] + '材质，边缘清晰');
  else parts.push('表面哑光质感，边缘清晰');
  parts.push('产品外观与包装在各段中完全一致');
  return parts.join('，');
}

function consistencyAnchor(o) {
  return [
    '【④ 一致性锚点】把这段粘在每条分镜提示词的最前面，否则各段会生成不同的人、不同的商品',
    `人物：${o.person}`,
    `商品：${o.prodAnchor || o.prod}`,
    `光线：全片统一${o.styleTone || '暖调'}，主光始终来自左前方，阴影方向不变`,
    `画质：全片同一套渲染风格，同样的色彩与对比度`,
    '提示：所有镜头里人物的五官、发型、衣着必须完全一致；商品的形状、颜色、logo 位置必须完全一致'
  ].join('\n');
}

function buildPrompt(o) {
  const shots = SHOT_BEATS.map(b => ({
    span: b.span,
    text: buildShotPrompt(o, b.key)
  }));
  const p1 = o.props && o.props[0] || '产品特写';
  const p2 = o.props && o.props[1] || '使用场景';
  const p3 = o.props && o.props[2] || '细节微距';

  return [
    '【① 剧情梗概】配音直接照这段念，不用改',
    o.story,
    '',
    '【② 分镜画面提示】每段一条，可分别粘贴给视频模型',
    ...shots.map(s => `${s.span}　${s.text}`),
    '',
    '【③ 整体风格】放在每段提示词开头或结尾，作为统一风格约束',
    `真实生活质感，广告感低，自然光，无磨皮滤镜。竖屏 9:16，分辨率 1080x1920，时长 8 秒左右，帧率 30fps。`,
    `色调：${o.styleTone || '暖调'}，饱和度适中，阴影柔和。`,
    `画面质感：${p1}、${p2}、${p3} 交替出现，产品细节清晰锐利。`,
    `禁止：过曝、塑料感、杂乱背景、多余文字、水印、变形的手指、多张脸。`,
    '',
    consistencyAnchor(o)
  ].join('\n');
}